CREATE OR REPLACE FUNCTION public.scrub_terminal_otp_secret()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.status IN ('VERIFIED', 'FAILED') THEN
    NEW.code := '';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS scrub_terminal_otp_secret_trigger ON public.otp_queue;
CREATE TRIGGER scrub_terminal_otp_secret_trigger
BEFORE INSERT OR UPDATE OF status, code
ON public.otp_queue
FOR EACH ROW
EXECUTE FUNCTION public.scrub_terminal_otp_secret();

UPDATE public.otp_queue
SET code = ''
WHERE status IN ('VERIFIED', 'FAILED')
  AND code <> '';

-- Historical worker logs may contain the WhatsApp message body and OTP code.
UPDATE public.otp_logs
SET message = CASE
  WHEN status = 'SENT' THEN 'OTP delivered through WhatsApp.'
  WHEN status = 'VERIFIED' THEN 'OTP verified successfully.'
  WHEN status = 'FAILED' THEN 'OTP delivery or verification failed.'
  ELSE 'OTP operational event.'
END
WHERE message IS NOT NULL;

